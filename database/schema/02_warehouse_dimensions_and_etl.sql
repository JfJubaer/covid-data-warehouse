CREATE TABLE IF NOT EXISTS warehouse.dim_date (
    date_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_date DATE NOT NULL UNIQUE,
    day SMALLINT NOT NULL CHECK (day BETWEEN 1 AND 31),
    month SMALLINT NOT NULL CHECK (month BETWEEN 1 AND 12),
    month_name VARCHAR(9) NOT NULL,
    quarter SMALLINT NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    year INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS warehouse.dim_location (
    location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country TEXT NOT NULL,
    division TEXT,
    district TEXT,
    population BIGINT CHECK (population IS NULL OR population >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT dim_location_natural_key
        UNIQUE NULLS NOT DISTINCT (country, division, district)
);

CREATE TABLE IF NOT EXISTS warehouse.dim_hospital (
    hospital_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_name TEXT NOT NULL,
    hospital_type TEXT,
    hospital_capacity BIGINT CHECK (
        hospital_capacity IS NULL OR hospital_capacity >= 0
    ),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS warehouse.dim_vaccine (
    vaccine_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vaccine_name TEXT NOT NULL,
    manufacturer TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT dim_vaccine_natural_key
        UNIQUE NULLS NOT DISTINCT (vaccine_name, manufacturer)
);

CREATE TABLE IF NOT EXISTS warehouse.etl_runs (
    etl_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_name TEXT NOT NULL,
    source_file TEXT,
    status TEXT NOT NULL DEFAULT 'running'
        CHECK (status IN ('running', 'succeeded', 'partial', 'failed')),
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,
    rows_read BIGINT NOT NULL DEFAULT 0 CHECK (rows_read >= 0),
    rows_loaded BIGINT NOT NULL DEFAULT 0 CHECK (rows_loaded >= 0),
    rows_rejected BIGINT NOT NULL DEFAULT 0 CHECK (rows_rejected >= 0),
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT etl_runs_finish_time_matches_status
        CHECK (
            (status = 'running' AND finished_at IS NULL)
            OR (status <> 'running' AND finished_at IS NOT NULL)
        )
);

CREATE TABLE IF NOT EXISTS warehouse.rejected_records (
    rejected_record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etl_run_id BIGINT NOT NULL
        REFERENCES warehouse.etl_runs (etl_run_id),
    source_table TEXT NOT NULL
        CHECK (
            source_table IN (
                'raw_covid_cases',
                'raw_hospitals',
                'raw_vaccinations',
                'raw_testing'
            )
        ),
    source_raw_id BIGINT,
    source_file TEXT,
    source_row_number BIGINT CHECK (
        source_row_number IS NULL OR source_row_number > 0
    ),
    rejection_reason TEXT NOT NULL,
    rejected_values JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
