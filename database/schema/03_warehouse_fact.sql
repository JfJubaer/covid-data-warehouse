CREATE TABLE IF NOT EXISTS warehouse.fact_covid (
    fact_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_id INTEGER NOT NULL REFERENCES warehouse.dim_date (date_id),
    location_id BIGINT NOT NULL
        REFERENCES warehouse.dim_location (location_id),
    hospital_id BIGINT REFERENCES warehouse.dim_hospital (hospital_id),
    vaccine_id BIGINT REFERENCES warehouse.dim_vaccine (vaccine_id),
    etl_run_id BIGINT REFERENCES warehouse.etl_runs (etl_run_id),
    new_cases BIGINT,
    total_cases BIGINT,
    deaths BIGINT,
    recoveries BIGINT,
    tests BIGINT,
    vaccinations BIGINT,
    icu_patients BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fact_covid_daily_location_hospital
        UNIQUE NULLS NOT DISTINCT (date_id, location_id, hospital_id)
);

COMMENT ON TABLE warehouse.fact_covid IS
    'Grain: one daily record per location and hospital. A NULL hospital_id identifies the location-level aggregate row; do not repeat location-wide measures on hospital rows.';
COMMENT ON COLUMN warehouse.fact_covid.vaccinations IS
    'Store a location-wide daily dose total only once on the row with hospital_id NULL. Aggregate across products first; do not duplicate this metric across hospitals or create one fact per vaccine.';
COMMENT ON COLUMN warehouse.fact_covid.vaccine_id IS
    'Optional product attribution only when the row represents exactly one vaccine. Leave NULL for multi-product or location-wide aggregate vaccination totals.';
