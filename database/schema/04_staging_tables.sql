CREATE TABLE IF NOT EXISTS staging.stg_covid_cases (
    staging_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etl_run_id BIGINT NOT NULL
        REFERENCES warehouse.etl_runs (etl_run_id),
    source_raw_id BIGINT NOT NULL
        REFERENCES raw_data.raw_covid_cases (raw_id),
    report_date DATE,
    country TEXT,
    division TEXT,
    district TEXT,
    population BIGINT,
    new_cases BIGINT,
    total_cases BIGINT,
    deaths BIGINT,
    recoveries BIGINT,
    icu_patients BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT stg_covid_cases_run_source
        UNIQUE (etl_run_id, source_raw_id)
);

