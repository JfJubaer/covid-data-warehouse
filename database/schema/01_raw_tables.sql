CREATE TABLE IF NOT EXISTS raw_data.raw_covid_cases (
    raw_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_file TEXT NOT NULL,
    source_row_number BIGINT NOT NULL CHECK (source_row_number > 0),
    imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    source_headers TEXT[] NOT NULL,
    source_values TEXT[] NOT NULL,
    source_line TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT raw_covid_cases_header_value_count
        CHECK (CARDINALITY(source_headers) = CARDINALITY(source_values))
);

